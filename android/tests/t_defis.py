"""Défis (hors ligne) : modes, partie contre ETO Brillant, jugement des coups, annulation, spectacle Titans, abandon, historique."""
from mobile_common import *

errs = []
with sync_playwright() as pw:
    b, ctx = launch(pw)
    pg = open_app(ctx, errs)
    open_tool(pg, "defis")
    check(pg.locator(".df-mode").count() == 19, "19 modes de défi affichés (Nasko pénoire, Naskurieux, GhorGhor, Naskolit, Jester, combat de bots)")
    check(pg.locator('.mtile[data-m="b-df"]').count() == 0, "plus de tuile « Défis » verrouillée")
    # --- partie contre E.N.O.S. (niveau bas) : on joue e2e4, le bot répond, chaque coup est jugé
    pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.launch('enos', {color: 'w', pow: 5, elo: 400})")
    pg.wait_for_selector("#df-board .cb-sq")
    pg.click('#df-board [data-sq="e2"]'); pg.click('#df-board [data-sq="e4"]')
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.moves.length >= 2", timeout=30000)
    g = pg.evaluate("(() => { const g = document.querySelector('#tool-defis .suite-body')._api.g; return {n: g.moves.length, k: g.moves.map(m => m.q.key), fen: g.fen, over: g.over}; })()")
    check(g["n"] >= 2 and all(k in ("brilliant", "book", "best", "excellent", "good", "inaccuracy", "mistake", "blunder") for k in g["k"]), "coups jugés : %s" % g["k"])
    check(pg.locator("#df-judge .kchip").count() == 1, "jugement affiché : " + pg.inner_text("#df-judge")[:60])
    # annuler (2 demi-coups)
    pg.wait_for_function("!document.querySelector('#tool-defis .suite-body')._api.g.busy", timeout=20000)
    pg.click("#b-undo")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.moves.length === 0", timeout=8000)
    check(pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.fen").startswith("rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP"), "annulation : retour à la position de départ")
    # abandon
    pg.click("#b-res"); pg.click(".sheet button >> text=ABANDONNER")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.over", timeout=5000)
    check("Abandon" in pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.over"), "abandon enregistré")
    pg.keyboard.press("Escape")
    # --- ETO Brillant : position où un sacrifice gagnant existe (Légal) -> ETO doit le jouer en tant que Blancs
    pg.evaluate("""() => { const a = document.querySelector('#tool-defis .suite-body')._api; a.launch('titans', {}); }""")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.moves.length >= 3", timeout=90000)
    check(True, "Choc des Titans : 3 demi-coups joués en spectacle")
    pg.click("#b-stop")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.over", timeout=8000)
    check(pg.evaluate("ENOS.settings.get('defi.hist', []).length") >= 1, "partie ajoutée à l'historique")
    # --- combats ETO Brillant + enregistrement complet + replay
    pg.wait_for_selector("#sheet .opt"); pg.click("#sheet .opt >> text=FERMER")
    pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.launch('ebs', {color: 'b'})")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.moves.length >= 3", timeout=90000)
    names = pg.evaluate("(() => { const g = document.querySelector('#tool-defis .suite-body')._api.g; return [g.pl.w.name, g.pl.b.name]; })()")
    check(names == ["Stockfish", "ETO Brillant"], "ETO Brillant vs Stockfish, ETO avec les Noirs : %s" % names)
    pg.click("#b-stop")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.over", timeout=8000)
    pg.wait_for_selector("#sheet .opt"); pg.click("#sheet .opt >> text=FERMER"); pg.click("#df-back")
    rec = pg.evaluate("ENOS.settings.get('defi.hist', []).slice(-1)[0]")
    check(rec.get("mv") and len(rec["mv"]) >= 3 and rec["mv"][0][0] and rec["pb"] == "ETO Brillant", "partie enregistrée en entier : %d coups" % len(rec.get("mv", [])))
    check(pg.locator("[data-rev]").count() >= 1, "bouton REVOIR présent")
    pg.locator("[data-rev]").first.click()
    pg.wait_for_selector("#rp-play")
    pg.click("#rp-last")
    check(pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.moves.length") == len(rec["mv"]), "replay : fin de partie atteinte")
    pg.click("#rp-first")
    check(pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.fen").startswith("rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP"), "replay : retour au début")
    pg.click("#rp-next"); pg.click("#rp-speed")
    check(pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.moves.length") == 1 and pg.inner_text("#rp-speed") == "2×", "replay : pas à pas + vitesse 2×")
    # --- bots de style : Nasko (Blancs) sort le Gambit Alien contre la Caro-Kann
    pg.wait_for_selector("#sheet .opt", timeout=2000) if pg.locator("#sheet .opt").count() else None
    pg.reload(); pg.wait_for_selector("#tabbar"); open_tool(pg, "defis")
    pg.wait_for_function("window.ENOS_STYLE && ENOS_STYLE.nasko && ENOS_STYLE.lelex", timeout=10000)
    check(pg.evaluate("ENOS_STYLE.nasko.eloEst") == 1300 and pg.evaluate("Object.keys(ENOS_STYLE.nasko.book.w).length") > 50, "profil Nasko chargé (livre d'ouvertures)")
    pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.launch('nasko', {color: 'b'})")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.moves.length >= 1", timeout=30000)
    check(pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.moves[0].san") == "e4", "Nasko ouvre 1.e4")
    for u in ("c7c6", "d7d5", "d5e4", "g8f6", "h7h6"):
        pg.wait_for_function("!document.querySelector('#tool-defis .suite-body')._api.g.busy", timeout=30000)
        pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.ch.turn() === 'b'", timeout=30000)
        pg.evaluate("(u) => { const a = document.querySelector('#tool-defis .suite-body')._api; a.g.sel = ''; }", u)
        pg.click('#df-board [data-sq="%s"]' % u[:2]); pg.click('#df-board [data-sq="%s"]' % u[2:4])
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.moves.length >= 11", timeout=60000)
    check(" ".join(pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.moves.map(m => m.san)")[:11]) == "e4 c6 d4 d5 Nc3 dxe4 Nxe4 Nf6 Ng5 h6 Nxf7", "Gambit Alien joué par Nasko : e4 c6 d4 d5 Nc3 dxe4 Nxe4 Nf6 Ng5 h6 Nxf7")
    # Lelex joue un coup légal hors livre
    pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.launch('lelex', {color: 'b'})")
    pg.wait_for_function("document.querySelector('#tool-defis .suite-body')._api.g.moves.length >= 1", timeout=30000)
    check(True, "Lelex répond : " + pg.evaluate("document.querySelector('#tool-defis .suite-body')._api.g.moves[0].san"))
    check(not errs, "aucune erreur JavaScript : %s" % errs)
print("\n%d échec(s)" % len(BAD))
